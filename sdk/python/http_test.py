"""HTTP wire contract parity tests for the Python SDK.

The golden fixtures are generated by the Go source of truth
(internal/wire: `go test -run TestHTTPGolden -update`) and shared by all three SDKs.
These tests exercise only serialization and the handler adapter - no running NATS is needed.

Run: python -m unittest http_test   (from sdk/python)
"""

import asyncio
import base64
import json
import os
import unittest

import aether

GOLDEN_DIR = os.path.join(os.path.dirname(__file__), "..", "..", "testdata", "wire", "http")


def golden(name):
    with open(os.path.join(GOLDEN_DIR, name + ".json"), "rb") as f:
        return f.read()


# The same logical cases as httpGoldenCases() in internal/wire/http_test.go, built through the typed
# dataclasses. Bodies are the base64 the Go []byte marshalled to.
CASES = {
    "req_get": aether.HTTPRequest(method="GET", path="/"),
    "req_post_binary": aether.HTTPRequest(
        method="POST", path="/upload",
        headers={"Content-Type": ["application/octet-stream"]}, body="AAH/EA=="),
    "req_query_multi": aether.HTTPRequest(
        method="GET", path="/search", query="q=cats&q=dogs&safe=1",
        headers={"Accept": ["text/html"], "X-Tag": ["a", "b"]}),
    "resp_html": aether.HTTPResponse(
        status=200, headers={"Content-Type": ["text/html; charset=utf-8"]}, body="PGgxPmhpPC9oMT4="),
    "resp_json": aether.HTTPResponse(
        status=201, headers={"Content-Type": ["application/json"]}, body="eyJvayI6dHJ1ZX0="),
    "resp_cookies": aether.HTTPResponse(
        status=200, headers={"Set-Cookie": ["a=1", "b=2"]}, body="b2s="),
    "resp_minimal": aether.HTTPResponse(status=204),
}


class HTTPParity(unittest.TestCase):
    def test_to_wire_matches_golden(self):
        for name, case in CASES.items():
            with self.subTest(case=name):
                self.assertEqual(case.to_wire(), json.loads(golden(name)))

    def test_from_wire_round_trip(self):
        for name, case in CASES.items():
            with self.subTest(case=name):
                raw = json.loads(golden(name))
                cls = aether.HTTPRequest if name.startswith("req_") else aether.HTTPResponse
                self.assertEqual(cls.from_wire(raw).to_wire(), raw)

    def test_binary_body_round_trips(self):
        body = bytes(range(256))
        b64 = base64.b64encode(body).decode("ascii")
        resp = aether.HTTPResponse(status=200, body=b64)
        self.assertEqual(resp.body_bytes(), body)

    def test_response_constructors(self):
        text = aether.text_response(200, "hi")
        self.assertEqual(text.status, 200)
        self.assertEqual(text.headers["Content-Type"][0], "text/plain; charset=utf-8")
        self.assertEqual(text.body_text(), "hi")

        html = aether.html_response(404, "<p>gone</p>")
        self.assertEqual(html.headers["Content-Type"][0], "text/html; charset=utf-8")
        self.assertEqual(html.body_text(), "<p>gone</p>")

        j = aether.json_response(201, {"ok": True})
        self.assertEqual(j.status, 201)
        self.assertEqual(j.body_text(), '{"ok":true}')

    def test_body_text_decodes_go_fixture(self):
        resp = aether.HTTPResponse.from_wire(json.loads(golden("resp_html")))
        self.assertEqual(resp.body_text(), "<h1>hi</h1>")

    def test_def_web_requires_handle(self):
        with self.assertRaises(ValueError):
            aether.def_web(name="x")

    def test_def_web_serves_request_and_threads_state(self):
        def handle(req, hits, ctx):
            return aether.html_response(200, f"path={req.path} hits={hits + 1}"), hits + 1

        defn = aether.def_web(name="web", init=lambda ctx: 0, handle=handle)
        adapter = defn.handle_call[aether.OP_HTTP_REQUEST]

        payload = {"method": "GET", "path": "/hello"}
        wire_resp, next_state = asyncio.run(adapter(payload, 4, None))
        self.assertEqual(next_state, 5)
        resp = aether.HTTPResponse.from_wire(wire_resp)
        self.assertEqual(resp.status, 200)
        self.assertEqual(resp.body_text(), "path=/hello hits=5")


if __name__ == "__main__":
    unittest.main()
