class WireParity(unittest.TestCase):
    def test_encode_matches_golden(self):
        # Field order and whitespace differ from Go, so compare parsed values, not bytes.
        for name, case in CASES.items():
            with self.subTest(case=name):
                self.assertEqual(json.loads(aether._encode(case)), json.loads(golden(name)))

    def test_round_trip(self):
        for name in CASES:
            with self.subTest(case=name):
                decoded = aether._decode(golden(name))
                self.assertEqual(json.loads(aether._encode(decoded)), json.loads(golden(name)))

    def test_sdk_builds_the_canonical_refusal_and_deadline_replies(self):
        # The replies the SDK itself builds must be the canonical wire form too: the refusal a
        # handler's Refuse produces and the answer to a call dropped past its deadline.
        req = {"v": 1, "id": "c-11", "kind": "call", "op": "withdraw"}
        refusal = aether.Refuse("insufficient_funds", "the balance is 3, the withdrawal 5")
        self.assertEqual(aether._refused_reply(req, refusal), json.loads(golden("reply_refused")))
        self.assertEqual(aether._expired_reply(req, 1200), json.loads(golden("reply_deadline_exceeded")))
        self.assertEqual(aether._too_large_reply(req, 1500000, 1048576), json.loads(golden("reply_too_large")))

    def test_heartbeat_metrics_payload_matches_the_contract(self):
        # A thrall that never dropped a call reports the payload it always did (no expired_total
        # key); one that did reports the count.
        stats = aether._MailboxStats()
        self.assertEqual(list(stats.snapshot()), ["mailbox_depth", "mailbox_latency_ms", "processed_total"])
        for _ in range(2):
            stats.begin()
            stats.drop()
        self.assertEqual(stats.snapshot(), {"mailbox_depth": 0, "mailbox_latency_ms": 0.0,
                                            "processed_total": 0, "expired_total": 2})

    def test_describe_dict_omits_empty_fields(self):
        # Empty fields are dropped to match the Go omitempty wire form.
        self.assertEqual(aether._describe_dict([], [], ""), {})
        self.assertEqual(aether._describe_dict(["get"], [], "1.0.0"),
                         {"call_ops": ["get"], "version": "1.0.0"})
        self.assertEqual(
            aether._describe_dict(["get"], ["inc"], "1.0.0", {"msg": "handler_error: boom", "ms": 42}),
            {"call_ops": ["get"], "cast_ops": ["inc"], "version": "1.0.0",
             "last_error": "handler_error: boom", "last_error_ms": 42})

    def test_fsm_describe(self):
        # Mirrors the Go TestFSMDescribe: the union of reaction ops as call and cast, plus _state.
        def _fn(ev, data, ctx):
            return aether.Outcome(data=data)
        defn = aether.FSM(
            name="gate", initial="idle", init=lambda ctx: 0, version="2.0.0",
            states={
                "idle": aether.State(on={"start": aether.Reaction(fn=_fn)}),
                "running": aether.State(on={"stop": aether.Reaction(fn=_fn), "start": aether.Reaction(fn=_fn)}),
            })
        d = aether._fsm_describe(defn)
        self.assertEqual(d["call_ops"], ["_state", "start", "stop"])
        self.assertEqual(d["cast_ops"], ["start", "stop"])
        self.assertEqual(d["version"], "2.0.0")

    def test_subjects(self):
        app, name = "demo", "counter"
        self.assertEqual(aether._sub_call(app, name), "aether.demo.counter.call")
        self.assertEqual(aether._sub_cast(app, name), "aether.demo.counter.cast")
        self.assertEqual(aether._sub_info(app, name), "aether.demo.counter.info")
        self.assertEqual(aether._sub_data(app, name), "aether.demo.counter.*")
        self.assertEqual(aether._stream(app, name), "aether_demo_counter")
        self.assertEqual(aether._sub_evt(app, name), "aether.demo.counter.evt")
        self.assertEqual(aether._stream_evt(app, name), "aether_demo_counter_evt")
        self.assertEqual(aether._sub_ctl(name), "aether._lord.counter.ctl")
        self.assertEqual(aether._sub_hb(name), "aether._lord.counter.hb")
        self.assertEqual(aether._sub_lord_ctl(), "aether._lord.ctl")


